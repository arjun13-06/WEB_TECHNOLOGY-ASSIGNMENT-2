package com.college.portal;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;

@WebServlet("/file")
public class FileServlet extends HttpServlet {
    @Override protected void doGet(HttpServletRequest request, HttpServletResponse response) throws ServletException, IOException {
        HttpSession session = request.getSession(false);
        if (session == null || session.getAttribute("loggedInUser") == null) { response.sendError(401, "Please log in."); return; }
        int id;
        try { id = Integer.parseInt(request.getParameter("id")); } catch (Exception e) { response.sendError(400, "Invalid file id."); return; }
        String storedName, mime, original;
        try (Connection con = DB.getConnection(); PreparedStatement ps = con.prepareStatement("SELECT stored_name,file_type,original_name FROM student_files WHERE id=?")) {
            ps.setInt(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) { response.sendError(404, "File not found."); return; }
                storedName = rs.getString("stored_name"); mime = rs.getString("file_type"); original = rs.getString("original_name");
            }
        } catch (SQLException e) { throw new ServletException("Could not look up file.", e); }
        // basename prevents path traversal; stored names are generated by the PHP upload handler.
        Path path = DB.UPLOAD_DIR.resolve(Path.of(storedName).getFileName().toString()).normalize();
        if (!path.startsWith(DB.UPLOAD_DIR) || !Files.isRegularFile(path)) { response.sendError(404, "Stored file is missing."); return; }
        response.setContentType(mime == null ? "application/octet-stream" : mime);
        response.setHeader("X-Content-Type-Options", "nosniff");
        response.setHeader("Content-Disposition", "inline; filename=\"" + original.replace("\"", "") + "\"");
        response.setContentLengthLong(Files.size(path));
        try (InputStream in = Files.newInputStream(path)) { in.transferTo(response.getOutputStream()); }
    }
}
